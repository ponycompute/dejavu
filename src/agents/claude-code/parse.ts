// Claude Code session log → normalized events.
// Logs live at ~/.claude/projects/<cwd with every non-alphanumeric turned into ->/<session-id>.jsonl,
// one JSON record per line. Assistant content blocks may be split across several records that
// share a message id, so every block is treated on its own.
import fs from "node:fs";
import type { Session, SessionEvent, SessionMeta, ToolResult } from "../../core/types.js";

type Json = any; // raw log records are loosely shaped

const SKIP_TEXT = [
  /^Caveat: The messages below were generated by the user/,
  /^\[Image: original \d+x\d+/,
  /^\[Request interrupted by user for tool use\]/,
  /^This session is being continued from a previous conversation/,
];

const STRIP_TAGS = /<(system-reminder|ide_opened_file|ide_selection|ide_diagnostics)>[\s\S]*?<\/\1>/g;

const tag = (text: string, name: string) => text.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`))?.[1];

function toolResultText(content: Json): string {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  return content
    .map((c: Json) => (c?.type === "text" ? c.text : c?.type === "image" ? "[Image]" : ""))
    .filter(Boolean)
    .join("\n");
}

export function parseClaudeCodeLines(lines: string[], file = "<memory>"): Session {
  const meta: SessionMeta = { sessionId: null, cwd: null, version: null, gitBranch: null, model: null, startedAt: null };
  const events: SessionEvent[] = [];
  const toolsById = new Map<string, Extract<SessionEvent, { kind: "tool" }>>();
  const countedMessages = new Set<string>();
  let images = 0;

  for (const line of lines) {
    if (!line.trim()) continue;
    let rec: Json;
    try {
      rec = JSON.parse(line);
    } catch {
      continue;
    }
    if (rec.isSidechain) continue; // subagent transcripts
    if (rec.type !== "user" && rec.type !== "assistant") continue;
    meta.cwd ??= rec.cwd ?? null;
    meta.version ??= rec.version ?? null;
    meta.gitBranch ??= rec.gitBranch ?? null;
    meta.sessionId ??= rec.sessionId ?? null;
    meta.startedAt ??= rec.timestamp ?? null;
    const ts = rec.timestamp ? Date.parse(rec.timestamp) : null;
    const msg = rec.message ?? {};

    if (rec.type === "assistant") {
      if (msg.model && msg.model !== "<synthetic>") meta.model ??= msg.model;
      const before = events.length;
      for (const block of Array.isArray(msg.content) ? msg.content : []) {
        if (block.type === "text" && block.text?.trim()) {
          if (/^(API Error|No response requested)/.test(block.text.trim()) && msg.model === "<synthetic>") continue;
          events.push({ kind: "assistant", text: block.text.trim(), ts });
        } else if (block.type === "thinking" || block.type === "redacted_thinking") {
          events.push({ kind: "thinking", ts, durationMs: rec.thinkingDurationMs ?? null });
        } else if (block.type === "tool_use" && !toolsById.has(block.id)) {
          const ev = { kind: "tool" as const, id: block.id, name: block.name, input: block.input ?? {}, result: null, ts, resultTs: null };
          toolsById.set(block.id, ev);
          events.push(ev);
        }
      }
      // one model message is often split over several records that repeat its usage
      const first = events[before];
      const tokens = msg.usage?.output_tokens;
      if (first && first.kind !== "user" && typeof tokens === "number" && msg.id && !countedMessages.has(msg.id)) {
        countedMessages.add(msg.id);
        (first as { tokens?: number }).tokens = tokens;
      }
      continue;
    }

    // user record: a prompt, a slash command, shell-mode input/output, or tool results
    if (rec.isMeta) continue;
    if (rec.isCompactSummary) {
      events.push({ kind: "compacted", ts });
      continue;
    }
    const content = msg.content;
    if (Array.isArray(content) && content.some((c: Json) => c?.type === "tool_result")) {
      for (const c of content) {
        if (c?.type !== "tool_result") continue;
        const ev = toolsById.get(c.tool_use_id);
        if (!ev) continue;
        const result: ToolResult = {
          text: toolResultText(c.content),
          isError: !!c.is_error,
          data: rec.toolUseResult && typeof rec.toolUseResult === "object" ? rec.toolUseResult : null,
        };
        ev.result = result;
        ev.resultTs = ts;
      }
      continue;
    }

    const parts: string[] = [];
    if (typeof content === "string") parts.push(content);
    else if (Array.isArray(content)) {
      for (const c of content) {
        if (c?.type === "text") parts.push(c.text);
        else if (c?.type === "image") parts.push(`[Image #${++images}]`);
      }
    }
    const text = parts
      .map((p) => p.replace(STRIP_TAGS, "").trim())
      .filter((p) => p && !SKIP_TEXT.some((re) => re.test(p)))
      .join("\n")
      .trim();
    if (!text) continue;

    if (/^\[Request interrupted by user/.test(text)) {
      events.push({ kind: "interrupted", ts });
      continue;
    }
    const command = tag(text, "command-name");
    if (command != null) {
      const args = tag(text, "command-args")?.trim() ?? "";
      const name = command.trim().startsWith("/") ? command.trim() : `/${command.trim()}`;
      events.push({ kind: "user", text: `${name} ${args}`.trim(), ts, command: true });
      continue;
    }
    const bash = tag(text, "bash-input");
    if (bash != null) {
      events.push({ kind: "user", text: `! ${bash.trim()}`, ts, command: true });
      continue;
    }
    const stdout = tag(text, "local-command-stdout") ?? tag(text, "bash-stdout");
    if (stdout != null || /^<(bash-stderr|local-command-stderr|command-message)>/.test(text)) {
      const out = [stdout, tag(text, "bash-stderr")].filter((s) => s?.trim()).join("\n").trim();
      if (out) events.push({ kind: "command-output", text: stripAnsi(out), ts });
      continue;
    }
    events.push({ kind: "user", text, ts });
  }

  return { agent: "claude-code", file, meta, events };
}

export function parseClaudeCode(file: string): Session {
  return parseClaudeCodeLines(fs.readFileSync(file, "utf8").split("\n"), file);
}

/** First real prompt in a log, read from the start of the file only. */
export function firstPrompt(file: string): string | null {
  const fd = fs.openSync(file, "r");
  try {
    const buf = Buffer.alloc(256 * 1024);
    const n = fs.readSync(fd, buf, 0, buf.length, 0);
    const lines = buf.subarray(0, n).toString("utf8").split("\n").slice(0, -1);
    const ev = parseClaudeCodeLines(lines).events.find((e) => e.kind === "user" && !e.command);
    return ev && ev.kind === "user" ? ev.text : null;
  } finally {
    fs.closeSync(fd);
  }
}

const stripAnsi = (s: string) => s.replace(/\x1b\[[0-9;]*[A-Za-z]/g, "");
